#!/usr/bin/env node
'use strict';

// Vercel build step: write public/config.js so the static frontend knows
// where the Socket.IO server lives (e.g. https://the-loom.onrender.com).
//   LOOM_SOCKET_URL=https://the-loom.onrender.com node scripts/write-config.js

const fs = require('fs');
const path = require('path');

const raw = (process.env.LOOM_SOCKET_URL || '').trim().replace(/\/+$/, '');
if (raw && !/^https?:\/\/[^\s"'<>]+$/.test(raw)) {
  console.error(`LOOM_SOCKET_URL is not an http(s) URL: ${raw}`);
  process.exit(1);
}
const out = path.join(__dirname, '..', 'public', 'config.js');
fs.writeFileSync(out, `// Generated by scripts/write-config.js at build time.\nwindow.LOOM_CONFIG = Object.freeze(${JSON.stringify({ socketUrl: raw })});\n`);
console.log(`wrote public/config.js (socketUrl: ${raw || '(same origin)'})`);
